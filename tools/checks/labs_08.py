def MaxValue(X, count=None):
    """Page: X[0..2n]; MaxVal(i,k), MinVal(i,k) over X[2i..2k]; rows i from n down to 0, each with k from i up to n."""
    n = len(X) // 2
    Mx, Mn = Memo(), Memo()
    for i in range(n, -1, -1):
        Mx[i, i] = Mn[i, i] = X[2 * i]
        for k in range(i + 1, n + 1):
            hi, lo = float("-inf"), float("inf")
            for j in range(i, k):
                if count is not None:
                    count[0] += 1
                if X[2 * j + 1] == "+":
                    hi = max(hi, Mx[i, j] + Mx[j + 1, k])
                    lo = min(lo, Mn[i, j] + Mn[j + 1, k])
                else:
                    hi = max(hi, Mx[i, j] - Mn[j + 1, k])
                    lo = min(lo, Mn[i, j] - Mx[j + 1, k])
            Mx[i, k], Mn[i, k] = hi, lo
    return Mx, Mn


def all_values(X):
    """Values of every full parenthesization (every binary tree over the operators)."""
    @lru_cache(maxsize=None)
    def vals(i, k):
        if i == k:
            return frozenset([X[2 * i]])
        out = set()
        for j in range(i, k):
            for a in vals(i, j):
                for b in vals(j + 1, k):
                    out.add(a + b if X[2 * j + 1] == "+" else a - b)
        return frozenset(out)
    return vals(0, len(X) // 2)


def all_trees(X):
    """Every full parenthesization as a string, for the examples."""
    @lru_cache(maxsize=None)
    def tr(i, k):
        if i == k:
            return [str(X[2 * i])]
        out = []
        for j in range(i, k):
            for a in tr(i, j):
                for b in tr(j + 1, k):
                    out.append(f"({a}{X[2 * j + 1]}{b})")
        return out
    return tr(0, len(X) // 2)


