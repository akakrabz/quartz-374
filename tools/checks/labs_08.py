def MinOnes(N, count=None):
    """Page: MinOnes(1) = 1; MinOnes(n) = min( min_{1<=m<=n/2} MinOnes(m)+MinOnes(n-m),
    min_{2<=m<=sqrt n, m | n} MinOnes(m)+MinOnes(n/m) ); filled for n increasing."""
    T = Memo()
    T[1] = 1
    for n in range(2, N + 1):
        best = float("inf")
        for m in range(1, n // 2 + 1):
            if count is not None:
                count[0] += 1
            best = min(best, T[m] + T[n - m])
        m = 2
        while m * m <= n:
            if n % m == 0:
                best = min(best, T[m] + T[n // m])
            m += 1
        T[n] = best
    return T


