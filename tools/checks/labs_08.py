def MinOnesPlusOne(N):
    T = {1: 1}
    for n in range(2, N + 1):
        best = T[n - 1] + 1
        m = 2
        while m * m <= n:
            if n % m == 0:
                best = min(best, T[m] + T[n // m])
            m += 1
        T[n] = best
    return T


