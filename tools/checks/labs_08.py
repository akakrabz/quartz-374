def next_table(R, L):
    """Next[i] (1-based) = smallest j in 1..n+1 with Ramp[j] > Ramp[i] + Length[i]; Ramp[n+1] = infinity."""
    n = len(R)
    return [None] + [bisect_right(R, R[i - 1] + L[i - 1]) + 1 for i in range(1, n + 1)]


def next_linear(R, L):
    """Same, by a linear scan (independent of the binary search)."""
    n = len(R)
    out = [None]
    for i in range(1, n + 1):
        j = 1
        while j <= n and not (R[j - 1] > R[i - 1] + L[i - 1]):
            j += 1
        out.append(j)
    return out


def MaxAir(R, L):
    """Page, Problem 1: MaxAir(i) = 0 if i > n, else max{MaxAir(i+1), Length[i] + MaxAir(Next(i))}; i from n+1 down."""
    n = len(R)
    Nx = next_table(R, L)
    M = Memo()
    M[n + 1] = 0
    for i in range(n, 0, -1):
        M[i] = max(M[i + 1], L[i - 1] + M[Nx[i]])
    return M


def MaxAirK(R, L, k):
    """Page, Problem 2: MaxAirK(i, l) = 0 if i > n or l = 0, else max{MaxAirK(i+1, l), Length[i] + MaxAirK(Next(i), l-1)}.
    Outer loop i from n+1 down to 1, inner loop l from 0 up to k."""
    n = len(R)
    Nx = next_table(R, L)
    M = Memo()
    for i in range(n + 1, 0, -1):
        for l in range(0, k + 1):
            if i > n or l == 0:
                M[i, l] = 0
            else:
                M[i, l] = max(M[i + 1, l], L[i - 1] + M[Nx[i], l - 1])
    return M


def MaxAirTwo(R, L, k, count=None):
    """Page, Problem 3: MaxAirTwo(i, j, a, b); outer i from n+1 down to 1, then j from n+1 down to 1, then a, b."""
    n = len(R)
    Nx = next_table(R, L)
    T = Memo()
    for i in range(n + 1, 0, -1):
        for j in range(n + 1, 0, -1):
            for a in range(k + 1):
                for b in range(k + 1):
                    if count is not None:
                        count[0] += 1
                    if i > n and j > n:
                        v = 0
                    elif i == j:
                        v = T[i + 1, i + 1, a, b]
                        if a >= 1:
                            v = max(v, L[i - 1] + T[Nx[i], i + 1, a - 1, b])
                        if b >= 1:
                            v = max(v, L[i - 1] + T[i + 1, Nx[i], a, b - 1])
                    elif i < j:
                        v = T[i + 1, j, a, b]
                        if a >= 1:
                            v = max(v, L[i - 1] + T[Nx[i], j, a - 1, b])
                    else:
                        v = T[i, j + 1, a, b]
                        if b >= 1:
                            v = max(v, L[j - 1] + T[i, Nx[j], a, b - 1])
                    T[i, j, a, b] = v
    return T


def MaxAirTwo_official(R, L, k, j_from_i=True, length_typo=True):
    """The official pseudocode as printed (indices -1..k with -infinity), optionally with its two misprints:
    j runs only from n+1 down to i, and the i > j case adds Length[i] instead of Length[j]."""
    n = len(R)
    Nx = next_table(R, L)
    L = list(L) + [0]  # the printed sentinel Length[n+1] = 0
    A = Memo()
    for i in range(n + 1, 0, -1):
        for j in range(n + 1, (i if j_from_i else 1) - 1, -1):
            for a in range(-1, k + 1):
                for b in range(-1, k + 1):
                    if a < 0 or b < 0:
                        A[i, j, a, b] = NEG
                    elif i == n + 1 and j == n + 1:
                        A[i, j, a, b] = 0
                    elif i == j:
                        A[i, j, a, b] = max(A[i + 1, i + 1, a, b], L[i - 1] + A[Nx[i], i + 1, a - 1, b],
                                            L[i - 1] + A[i + 1, Nx[i], a, b - 1])
                    elif i < j:
                        A[i, j, a, b] = max(A[i + 1, j, a, b], L[i - 1] + A[Nx[i], j, a - 1, b])
                    else:
                        Lx = L[i - 1] if length_typo else L[j - 1]
                        A[i, j, a, b] = max(A[i, j + 1, a, b], Lx + A[i, Nx[j], a, b - 1])
    return A[1, 1, k, k]


def brute_one(R, L, k=None):
    """Simulate every sequence of decisions of one sledder: at each ramp reached on the ground, jump or not.
    A ramp at position p is reached on the ground iff p > the landing point of the previous jump."""
    n = len(R)
    best = 0

    def go(i, land, used, air):
        nonlocal best
        if i == n:
            best = max(best, air)
            return
        go(i + 1, land, used, air)
        if R[i] > land and (k is None or used < k):
            go(i + 1, R[i] + L[i], used + 1, air + L[i])

    go(0, float("-inf"), 0, 0)
    return best


def reachable_on_ground(R, L, S):
    """True iff a sledder who jumps exactly at the ramps of S (0-based) reaches each of them on the ground."""
    land = float("-inf")
    for s in sorted(S):
        if not R[s] > land:
            return False
        land = R[s] + L[s]
    return True


def brute_two(R, L, k):
    """Every assignment of each ramp to nobody, Amy or Banjin (each ramp used at most once)."""
    n = len(R)
    best = 0
    for asg in itertools.product((0, 1, 2), repeat=n):
        A = [s for s in range(n) if asg[s] == 1]
        B = [s for s in range(n) if asg[s] == 2]
        if len(A) <= k and len(B) <= k and reachable_on_ground(R, L, A) and reachable_on_ground(R, L, B):
            best = max(best, sum(L[s] for s in A + B))
    return best


def best_subset(R, L, k=None):
    n = len(R)
    best, arg = 0, ()
    for r in range(n + 1):
        if k is not None and r > k:
            break
        for S in itertools.combinations(range(n), r):
            if reachable_on_ground(R, L, S):
                v = sum(L[s] for s in S)
                if v > best:
                    best, arg = v, S
    return best, arg


def rand_ramps(n, span, maxlen, zero=False):
    R = sorted(random.randint(0, span) for _ in range(n))  # duplicates allowed
    L = [random.randint(0 if zero else 1, maxlen) for _ in range(n)]
    return R, L


