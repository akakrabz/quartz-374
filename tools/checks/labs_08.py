def best_intervals(R, L):
    """Weighted class scheduling: max total length of pairwise compatible closed intervals [R, R+L]
    (book's convention: compatible iff one starts strictly after the other finishes)."""
    n = len(R)
    best = 0
    for r in range(n + 1):
        for S in itertools.combinations(range(n), r):
            if all(R[a] > R[b] + L[b] or R[b] > R[a] + L[a] for a, b in itertools.combinations(S, 2)):
                best = max(best, sum(L[s] for s in S))
    return best


