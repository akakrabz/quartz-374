def in_halfwit(w):
    """w ∈ {0^n1^n} • 2*0* • {1^n2^n}"""
    n = len(w)
    for i in range(n + 1):
        ex = runs(w[:i], "01")
        if ex is None or ex[0] != ex[1]:
            continue
        for j in range(i, n + 1):
            if runs(w[i:j], "20") is None:
                continue
            ez = runs(w[j:], "12")
            if ez is not None and ez[0] == ez[1]:
                return True
    return False


