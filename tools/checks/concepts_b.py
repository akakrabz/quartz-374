def moore_sync(D):
    """Synchronous Moore passes: list of the sets of pairs marked initially and in each pass."""
    R = D.reachable()
    Q = [q for q in D.states if q in R]
    pairs = [frozenset((p, q)) for i, p in enumerate(Q) for q in Q[i + 1:]]
    marked = {pq for pq in pairs if len({x in D.accepting for x in pq}) == 2}
    passes = [set(marked)]
    while True:
        new = set()
        for pq in pairs:
            if pq in marked:
                continue
            p, q = tuple(pq)
            if any(D.delta(p, a) != D.delta(q, a) and frozenset((D.delta(p, a), D.delta(q, a))) in marked
                   for a in D.alphabet):
                new.add(pq)
        passes.append(new)
        if not new:
            return passes, marked
        marked |= new


