def node_counts(G, w):
    """Set of numbers of nonterminal nodes over all parse trees of a non-empty w (CNF grammar)."""
    memo = {}

    def nc(A, i, j):
        key = (A, i, j)
        if key not in memo:
            out = set()
            for r in G.rules[A]:
                if len(r) == 1 and not G.is_nonterminal(r[0]):
                    if j - i == 1 and w[i] == r[0]:
                        out.add(1)
                elif len(r) == 2:
                    for m in range(i + 1, j):
                        out |= {1 + x + y for x in nc(r[0], i, m) for y in nc(r[1], m, j)}
            memo[key] = out
        return memo[key]

    return nc(G.start, 0, len(w))


