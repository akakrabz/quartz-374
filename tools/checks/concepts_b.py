def guess0(M):
    """{del0(w) : w ∈ L(M)}: an NFA that guesses the deleted 0s with ε-transitions."""
    delta = {}
    for q in M.states:
        delta[(q, EPS)] = {M.delta(q, "0")}
        delta[(q, "1")] = {M.delta(q, "1")}
    return NFA(M.alphabet, M.states, M.start, M.accepting, delta)


