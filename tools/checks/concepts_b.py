def cfg_cap_dfa(G, D):
    """Triple construction: nonterminal (p, A, q) generates the strings of L(A) that drive D from p to q."""
    Q = D.states
    rules = {(p, A, q): [] for p in Q for A in G.nonterminals for q in Q}
    for A, rhss in G.rules.items():
        for rhs in rhss:
            for seq in itertools.product(Q, repeat=len(rhs) + 1):
                body = []
                for k, X in enumerate(rhs):
                    p, q = seq[k], seq[k + 1]
                    if G.is_nonterminal(X):
                        body.append((p, X, q))
                    elif D.delta(p, X) == q:
                        body.append(X)
                    else:
                        break
                else:
                    rules[(seq[0], A, seq[-1])].append(tuple(body))
    rules[("start",)] = [((D.start, G.start, f),) for f in D.accepting]
    return CFG(("start",), rules, G.terminals)


