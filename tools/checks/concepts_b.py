def count_trees(G, w, start=None):
    """Number of parse trees of w; handles ε-rules and unit rules as long as there is no cycle."""
    memo, active = {}, set()
    nul = G.nullable()

    def nt(A, i, j):
        key = (A, i, j)
        if key in memo:
            return memo[key]
        if key in active:
            raise ValueError("infinitely many parse trees (cycle)")
        active.add(key)
        total = sum(seq(r, 0, i, j) for r in G.rules[A])
        active.discard(key)
        memo[key] = total
        return total

    def seq(r, k, i, j):
        if k == len(r):
            return 1 if i == j else 0
        X = r[k]
        if not G.is_nonterminal(X):
            return seq(r, k + 1, i + 1, j) if i < j and w[i] == X else 0
        lo = i if X in nul else i + 1                     # only nullable symbols may derive an empty span
        return sum(nt(X, i, m) * seq(r, k + 1, m, j) for m in range(lo, j + 1))

    return nt(start or G.start, 0, len(w))


def leftmost_step(G, form, nxt):
    """True iff nxt follows from form by rewriting the leftmost nonterminal with some rule."""
    for k, X in enumerate(form):
        if G.is_nonterminal(X):
            return any(form[:k] + "".join(r) + form[k + 1:] == nxt for r in G.rules[X])
    return False


