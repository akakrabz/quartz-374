def runs(w, order):
    """(e1, e2, ...) if w = order[0]^e1 order[1]^e2 ... (greedy block split), else None."""
    out, i = [], 0
    for c in order:
        j = i
        while j < len(w) and w[j] == c:
            j += 1
        out.append(j - i)
        i = j
    return tuple(out) if i == len(w) else None


def same_language(G, pred, alphabet, maxlen, start=None):
    """Shortest string on which the grammar (from `start`) and the predicate disagree, or None."""
    return first_difference(lambda w: G.generates(w, start), pred, alphabet, maxlen)


