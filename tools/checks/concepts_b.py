class RA:
    """Recursive automaton: modules {A: (s_A, t_A, {(q, x): {p}})}, x a terminal, EPS or a module name."""

    def __init__(self, modules, main):
        self.modules, self.main = modules, main
        self.out, self.final = {}, {}
        for A, (s, t, d) in modules.items():
            self.final[t] = A
            for (q, x), P in d.items():
                for p in P:
                    self.out.setdefault(q, []).append((x, p))

    def successors(self, conf, w):
        i, q, stack = conf
        for x, p in self.out.get(q, []):
            if x == EPS:
                yield (i, p, stack)
            elif x in self.modules:                       # call: push the return state, jump to s_x
                yield (i, self.modules[x][0], stack + (p,))
            elif i < len(w) and w[i] == x:                # read
                yield (i + 1, p, stack)
        if q in self.final and stack:                     # return: pop
            yield (i, stack[-1], stack[:-1])

    def accepts(self, w):
        s, t, _ = self.modules[self.main]
        start, goal = (0, s, ()), (len(w), t, ())
        seen, queue = {start}, deque([start])
        while queue:
            c = queue.popleft()
            if c == goal:
                return True
            for d in self.successors(c, w):
                if len(d[2]) <= len(w) + 2 and d not in seen:
                    seen.add(d)
                    queue.append(d)
        return False

    def to_cfg(self):
        """Lemma 5.6: [q] -> a[p] | [p] | [s_B][p], [t_A] -> ε, start [s_main]."""
        rules = {}
        for A, (s, t, d) in self.modules.items():
            for (q, x), P in d.items():
                for p in P:
                    body = (f"[{p}]",) if x == EPS else ((f"[{self.modules[x][0]}]", f"[{p}]") if x in self.modules
                                                         else (x, f"[{p}]"))
                    rules.setdefault(f"[{q}]", []).append(body)
            rules.setdefault(f"[{t}]", []).append(())
        return CFG(f"[{self.modules[self.main][0]}]", rules)


